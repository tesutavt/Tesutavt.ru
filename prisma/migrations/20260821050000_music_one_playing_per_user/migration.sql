-- Гонка при добавлении нескольких треков почти одновременно (например,
-- подряд заказанные песни в чате) могла привести к тому, что ДВА трека
-- одновременно помечались status='playing' для одного пользователя -
-- очередь после этого вела себя нестабильно: треки прерывались, не
-- доигрывая, и пропускались без реального воспроизведения.
--
-- Partial unique index не представим в текущем синтаксисе schema.prisma
-- (@@unique накрыл бы ВСЕ статусы, а не только 'playing'), поэтому
-- добавлен здесь напрямую как raw SQL.
CREATE UNIQUE INDEX "MusicTrack_one_playing_per_user"
  ON "MusicTrack" ("userId")
  WHERE "status" = 'playing';
